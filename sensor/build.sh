#!/bin/sh
# Build the wifisense sampler with the Xcode Command Line Tools (swiftc); full Xcode is not needed.
# Produces a universal (arm64 + x86_64) binary when the toolchain can, else a native one.
#   sensor/build.sh            universal if possible
#   sensor/build.sh --native   this Mac's architecture only
set -eu
cd "$(dirname "$0")"
# Deployment target: macOS 11 (Big Sur, the oldest macOS on Apple silicon; every public API used is
# 10.10+). Recent Command Line Tools no longer ship the x86_64 Swift back-deployment shims, so there
# the Intel slice falls back to macOS 13. MINS lists the targets tried in order.
MINS="11.0 13.0"
VERSION=$(sed -n 's/^version *= *"\(.*\)"/\1/p' ../engine/pyproject.toml | head -1)
[ -n "$VERSION" ] || { echo "build.sh: cannot read the version from engine/pyproject.toml" >&2; exit 1; }
command -v swiftc >/dev/null 2>&1 || {
  echo "build.sh: swiftc not found. Install the Command Line Tools: xcode-select --install" >&2; exit 1; }

TMP=$(mktemp -d "${TMPDIR:-/tmp}/wifisense-build.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
printf '// generated by build.sh\nlet SAMPLER_VERSION = "%s"\n' "$VERSION" > "$TMP/Version.swift"

build() {  # $1 = arch, $2 = output; sets MIN_<arch>
  for m in $MINS; do
    # Sources listed explicitly (not in a variable) so paths with spaces survive.
    if swiftc -O -swift-version 5 -target "$1-apple-macos$m" -framework CoreWLAN -framework Foundation \
        Sources/main.swift Sources/IOReport.swift Sources/Pinger.swift "$TMP/Version.swift" \
        -o "$2" 2> "$TMP/err-$1.txt"; then
      eval "MIN_$1=$m"; return 0
    fi
  done
  return 1
}

NATIVE=$(uname -m)
if [ "${1:-}" != "--native" ] && build arm64 "$TMP/wifisense-arm64" && build x86_64 "$TMP/wifisense-x86_64"; then
  lipo -create -output "$TMP/wifisense" "$TMP/wifisense-arm64" "$TMP/wifisense-x86_64"
  KIND="universal (arm64 macOS $MIN_arm64+, x86_64 macOS $MIN_x86_64+)"
else
  [ "${1:-}" = "--native" ] || echo "build.sh: universal build failed, building for $NATIVE only" >&2
  if ! build "$NATIVE" "$TMP/wifisense"; then
    cat "$TMP/err-$NATIVE.txt" >&2; exit 1
  fi
  eval "KIND=\"$NATIVE macOS \$MIN_$NATIVE+\""
fi
# Replace atomically so a running engine restarting the sampler never sees a half-written file.
mv -f "$TMP/wifisense" ./wifisense.new && mv -f ./wifisense.new ./wifisense
echo "built $(pwd)/wifisense $VERSION, $KIND"
